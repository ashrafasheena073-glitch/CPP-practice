#include <iostream>
using namespace std;
int main(){
	// swaping with operators 
	// addition and subtraction
	int a=18;
	int b=19;
	cout<<" before swaping "<< endl;
	cout << "a="<<a <<endl;
	cout << "b="<<b <<endl;
	a=a+b;
	b=a-b;
	a=a-b;
	cout << "after swaping "<<endl;
	cout<< "a=" << a <<endl;
	cout<< "b=" <<b <<endl;
	

	
	
return 0;	
}
